def render_items(group: dict) -> list[dict]:
    """화면에 내보낼 항목 = 링크가 확인된 것만. 주소를 아직 못 채운 항목은
    코드에 남아 있되(뼈대) 렌더되지 않는다."""
    return [i for i in group.get("items", []) if i.get("url")]


def guide() -> list[dict]:
    """렌더할 묶음만(항목이 하나도 없는 묶음은 통째로 뺀다)."""
    out = []
    for g in GUIDE:
        items = render_items(g)
        if items:
            out.append({**g, "items": items})
    return out


def pending() -> list[str]:
    """주소를 아직 못 채운 항목(빌드 로그에 찍어 잊히지 않게 한다)."""
    return [f'{g["name"]} / {i["name"]}' for g in GUIDE
            for i in g.get("items", []) if not i.get("url")]

