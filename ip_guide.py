def staown_power(data: dict | None) -> dict:
    """staown.json → 전력 설비·계통에 닿는 것만. 없으면 빈 구조."""
    if not data:
        return {}
    out = {"generated": data.get("generated", ""), "free": [], "pay": []}
    for kind in ("free", "pay"):
        for it in data.get(kind) or []:
            title = it.get("selTitle") or ""
            if not any(t in title for t in POWER_TERMS):
                continue
            out[kind].append({
                "title": title,
                "org": it.get("pemUser") or "",
                "type": it.get("selTypedesc") or "",
                "no": it.get("outNo") or "",
                "date": it.get("createDate") or "",
            })
    return out if (out["free"] or out["pay"]) else {}


